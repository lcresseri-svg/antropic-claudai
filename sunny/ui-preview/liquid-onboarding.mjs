import {chromium,browserOptions} from './browser.mjs';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const out=process.env.SUNNY_EVIDENCE||'/workspace/ui3-onboarding';await mkdir(out,{recursive:true});
const browser=await chromium.launch(browserOptions);
try {for(const theme of ['light','dark']){
const page=await browser.newPage({viewport:{width:390,height:844}});
await page.route('**/*',r=>new URL(r.request().url()).hostname==='127.0.0.1'?r.continue():r.abort());
await page.goto(`http://127.0.0.1:4177/ui-preview/index.html?ui=3&theme=${theme}&login`);
await page.getByRole('button',{name:'Continua con Google'}).click();
await page.getByText('Accesso di prova non riuscito. Riprova.').waitFor();await page.screenshot({path:`${out}/login-${theme}.png`});
await page.goto(`http://127.0.0.1:4177/ui-preview/index.html?ui=3&theme=${theme}&onboarding`);
await page.getByRole('button',{name:'Inizia',exact:true}).click();
await page.getByRole('button',{name:'Continua senza scegliere'}).click();
await page.getByPlaceholder('Es. Conto principale').fill('Conto di prova');
await page.getByPlaceholder('Es. 1250').fill('1250');
await page.getByRole('button',{name:'Passaggio precedente'}).click();
await page.getByRole('button',{name:'Continua senza scegliere'}).click();
assert.equal(await page.getByPlaceholder('Es. Conto principale').inputValue(),'Conto di prova');
await page.getByRole('button',{name:'Crea conto'}).click();
await page.getByRole('button',{name:/Esplora con dati di esempio/}).click();
await page.getByRole('alertdialog').waitFor();
await page.getByRole('button',{name:'Aggiungi dati di esempio',exact:true}).click();
await page.getByRole('alertdialog').getByText(/Impossibile aggiungere/).waitFor();
await page.screenshot({path:`${out}/demo-error-${theme}.png`});
await page.keyboard.press('Escape');
await page.getByRole('button',{name:/Importa un file/}).click();
await page.getByRole('dialog',{name:/Importa/}).waitFor();
await page.keyboard.press('Escape');
await page.getByRole('button',{name:/Inserisco a mano/}).click();
await page.getByRole('button',{name:'300 €',exact:true}).click();
await page.getByRole('button',{name:'Continua',exact:true}).click();
await page.getByRole('alert').waitFor();
await page.screenshot({path:`${out}/savings-error-${theme}.png`});
await page.getByRole('button',{name:'Decido dopo'}).click();
await page.screenshot({path:`${out}/ready-${theme}.png`});
assert.equal(await page.locator('body').evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
// Successful demo is reused after Back; slow savings writes own navigation.
await page.goto(`http://127.0.0.1:4177/ui-preview/index.html?ui=3&theme=${theme}&onboarding&onboardingMemory&slowIo`);
await page.getByRole('button',{name:'Inizia',exact:true}).click();
await page.getByRole('button',{name:'Continua senza scegliere'}).click();
await page.getByRole('button',{name:'Crea conto'}).click();
await page.getByRole('button',{name:/Esplora con dati di esempio/}).click();
await page.getByRole('button',{name:'Aggiungi dati di esempio',exact:true}).click();
await page.getByRole('button',{name:'Decido dopo'}).waitFor();
const writes=await page.evaluate(()=>window.__previewServiceWrites.count);assert.equal(writes,1);
await page.getByRole('button',{name:'Passaggio precedente'}).click();
await page.getByRole('button',{name:/Esplora con dati di esempio/}).click();
assert.equal(await page.getByRole('alertdialog').count(),0);
assert.equal(await page.evaluate(()=>window.__previewServiceWrites.count),writes);
await page.getByRole('button',{name:'300 €',exact:true}).click();
await page.getByRole('button',{name:'Continua',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'Passaggio precedente'}).count(),0);
assert.equal(await page.getByRole('button',{name:'Salta configurazione'}).count(),0);
await page.getByRole('button',{name:'Decido dopo'}).waitFor({state:'hidden'});
assert.equal(await page.evaluate(()=>window.__previewServiceWrites.count),2);
console.log(`PASS ${theme}: demo no duplicates, slow write navigation guard; login error, onboarding back/draft, create, demo confirmation/error, real importer, savings error/retry enabled, ready`);await page.close();
}}finally{await browser.close();}
