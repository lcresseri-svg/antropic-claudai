import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const require=createRequire(process.env.SUNNY_NODE_PACKAGES+'/package.json');
const {chromium}=require('playwright');
const browser=await chromium.launch({headless:true,channel:'msedge'});
const output=new URL('../../docs/product/piano-evidence/',import.meta.url);
mkdirSync(output,{recursive:true});
const errors=[];
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',r=>new URL(r.request().url()).hostname==='127.0.0.1'?r.continue():r.abort());
  const start=async(q='')=>{
    await page.goto('http://127.0.0.1:4177/ui-preview/index.html?'+q);
    await page.locator('#preview-writes').waitFor();
    await page.evaluate(()=>localStorage.clear());
    await page.getByRole('link',{name:'Piano',exact:true}).first().click();
    await page.getByRole('heading',{name:'Piano',exact:true}).waitFor();
  };
  await start('theme=dark');
  await page.locator('.piano-page').waitFor();
  for(const width of [390,768,1440])for(const theme of ['light','dark']){
    await page.setViewportSize({width,height:1000});
    const light=await page.locator('html').evaluate(e=>e.classList.contains('light'));
    if(light!==(theme==='light'))await page.getByRole('button',{name:'Cambia tema test'}).click();
    await page.locator('#app-scroll').evaluate(e=>e.scrollTop=0);
    assert(await page.locator('.piano-page').evaluate(e=>e.scrollWidth<=e.clientWidth+1),'horizontal overflow');
    await page.screenshot({path:fileURLToPath(new URL(`piano-${width}-${theme}.png`,output)),fullPage:true});
  }
  await page.setViewportSize({width:390,height:900});
  const trigger=page.getByRole('button',{name:'Come è calcolato',exact:true});
  await trigger.focus();await page.keyboard.press('Enter');
  await page.getByRole('dialog',{name:'Come è calcolato'}).waitFor();
  await page.keyboard.press('Escape');
  assert(await trigger.evaluate(e=>e===document.activeElement),'detail restores focus');
  const edit=page.getByRole('button',{name:'Modifica piano',exact:true});
  await edit.click();
  const dialog=page.getByRole('dialog',{name:'Modifica piano'});
  await dialog.getByRole('button',{name:'2. Obiettivi',exact:true}).click();
  const savings=dialog.getByRole('textbox',{name:'Risparmio da mantenere',exact:true});
  const original=await savings.inputValue();
  await savings.fill('');
  await dialog.getByRole('button',{name:'Annulla',exact:true}).click();
  await dialog.getByRole('button',{name:'Scarta',exact:true}).click();
  assert.equal(await page.locator('#preview-plan-writes').textContent(),'0');
  await edit.click();await dialog.getByRole('button',{name:'2. Obiettivi',exact:true}).click();
  assert.equal(await savings.inputValue(),original);
  await savings.fill('350,50');
  await dialog.getByRole('button',{name:'Salva modifiche',exact:true}).click();
  await dialog.waitFor({state:'detached'});
  assert.equal(await page.locator('#preview-plan-writes').textContent(),'1');
  await page.getByRole('button',{name:'Aggiungi spesa programmata',exact:true}).click();
  await page.getByText(/Spesa programmata registrata:/).waitFor();
  assert.equal(await page.locator('#preview-writes').textContent(),'0','opening a future expense must not write');
  await page.keyboard.press('Escape');
  // Each failure mode uses a fresh fixture store. Real Firebase transactions
  // are exercised separately in emulator tests, never inferred from this mock.
  await start('failSave&theme=dark');
  await page.getByRole('button',{name:/Risparmio da mantenere/}).click();
  await savings.fill('321,25');
  await dialog.getByRole('button',{name:'Salva modifiche',exact:true}).click();
  await dialog.getByRole('alert').waitFor();
  assert.equal(await savings.inputValue(),'321,25');
  assert.equal(await page.locator('#preview-plan-writes').textContent(),'0');
  await page.screenshot({path:fileURLToPath(new URL('piano-save-error.png',output))});
  await start('conflict&theme=light');
  await page.getByRole('button',{name:/Risparmio da mantenere/}).click();await savings.fill('333');
  await dialog.getByRole('button',{name:'Salva modifiche',exact:true}).click();
  await dialog.getByRole('button',{name:'Ricarica piano',exact:true}).waitFor();
  assert.equal(await savings.inputValue(),'333');
  await page.screenshot({path:fileURLToPath(new URL('piano-conflict.png',output))});
  await dialog.getByRole('button',{name:'Ricarica piano',exact:true}).click();
  await dialog.getByRole('button',{name:'Salva modifiche',exact:true}).click();await dialog.waitFor({state:'detached'});
  assert.equal(await page.locator('#preview-plan-writes').textContent(),'1');
  await start('empty&theme=light');
  await page.getByRole('heading',{name:'Creiamo il tuo primo piano'}).waitFor();
  assert.equal(await page.locator('.plan-number').count(),0);
  await page.getByRole('button',{name:'Completa il piano',exact:true}).click();
  await dialog.getByRole('textbox').first().fill('0');
  await dialog.getByRole('button',{name:'2. Obiettivi',exact:true}).click();
  await savings.fill('0');
  await dialog.getByRole('checkbox',{name:/Ho verificato/}).check();
  await dialog.getByRole('button',{name:'3. Spese',exact:true}).click();
  await page.screenshot({path:fileURLToPath(new URL('piano-first-plan.png',output))});
  await dialog.getByRole('button',{name:'Conferma piano',exact:true}).click();await dialog.waitFor({state:'detached'});
  assert.match(await page.locator('.plan-number').textContent(),/0,00/);
  await start('ui=2');
  assert.equal(await page.locator('.piano-page').count(),1,'Piano is available in current UI2');
  await start('user=normal');
  assert.equal(await page.locator('.piano-page').count(),1,'ordinary user gets Piano without entering UI3');
  assert.equal(await page.locator('html').getAttribute('data-ui-version'),'2.0');
  assert.deepEqual(errors,[]);
  console.log('Piano browser matrix and cancel/save/error/conflict/zero/current-UI checks passed.');
} finally {await browser.close();}
